class Solution {
  public int characterReplacement(String s, int k) {
        // Храним частоту каждого символа в текущем окне [left, right].
        // HashMap используется вместо int[26], так как символы могут быть любыми
        // (не только заглавные латинские буквы).
        Map<Character, Integer> count = new HashMap<>();

        int left = 0;       // левая граница скользящего окна
        int maxCount = 0;   // максимальная частота одного символа, встреченная
                             // за всё время движения правой границы (не уменьшается
                             // при сжатии окна — это допустимо, см. пояснение ниже)
        int result = 0;     // ответ — длина самого длинного валидного окна

        // Двигаем правую границу окна по всей строке
        for (int right = 0; right < s.length(); right++) {
            char c = s.charAt(right);

            // Увеличиваем счётчик текущего символа на 1.
            // getOrDefault нужен, т.к. символ может встречаться впервые
            count.put(c, count.getOrDefault(c, 0) + 1);

            // Обновляем максимальную частоту символа в окне.
            // Смысл: если в окне есть буква, встречающаяся maxCount раз,
            // то остальные (windowSize - maxCount) символов можно заменить на неё
            maxCount = Math.max(maxCount, count.get(c));

            // Текущий размер окна
            int windowSize = right - left + 1;

            // Проверяем валидность окна: сколько символов нужно заменить,
            // чтобы окно стало состоять из одной буквы (самой частой).
            // Если это число больше k — окно невалидно, нужно сжать его слева.
            if (windowSize - maxCount > k) {
                char leftChar = s.charAt(left);

                // Уменьшаем счётчик символа, который "выходит" из окна слева
                count.put(leftChar, count.get(leftChar) - 1);

                // Сдвигаем левую границу окна вправо (сжимаем окно на 1)
                left++;

                // Примечание: maxCount мы НЕ уменьшаем даже после сжатия окна.
                // Это может привести к тому, что maxCount станет "устаревшим"
                // (больше, чем реальный максимум в новом окне), но на корректность
                // ответа это не влияет: result уже не может уменьшиться,
                // а окно просто не будет расширяться дальше, чем позволяет
                // текущий (возможно завышенный) maxCount — то есть result
                // никогда не будет посчитан неверно в большую сторону.
            }

            // Обновляем результат: сравниваем текущий размер окна
            // (после возможного сжатия) с лучшим найденным
            result = Math.max(result, right - left + 1);
        }

        return result;
    }
    }
